import { test, expect } from "@playwright/test";

test("a beginner follows the course, revisits a mistake and resumes from saved answers", async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/#library");
  const course = page.getByRole("region", { name: "はじめての学習コース" });
  await expect(course.locator("li")).toHaveCount(4);
  await course.getByRole("link", { name: /線形探索を始める/ }).click();
  await expect(page.locator(".course-diagram")).toContainText("探す数　5");
  await expect(page.locator("#lessonInput")).toBeHidden();
  await page.locator("#traceNext").click();
  await expect(page.locator(".guide-tile.selected")).toContainText("7");
  await page.getByRole("button", { name: "一致する", exact: true }).click();
  await expect(page.locator(".prediction-feedback")).toContainText("次は右隣");
  await page.getByRole("button", { name: "一致しない" }).click();
  await expect(page.locator(".prediction-feedback")).toContainText("正解");
  await expect(page.locator("#progress")).toHaveText("0 / 34");
  await page.getByRole("button", { name: "コードを読む" }).click();
  await expect(page.locator("#sourceHeading")).toBeFocused();
  await page.getByRole("button", { name: "理解度をチェック" }).click();
  await expect(page.locator("#quizHeading")).toBeFocused();
  await page.getByRole("button", { name: "2", exact: true }).click();
  await page.getByRole("button", { name: "図と手順で復習する" }).click();
  await expect(page.locator("#traceSeek")).toHaveValue("0");
  await expect(page.locator("#observeHeading")).toBeFocused();
  await page.getByRole("link", { name: "全教材を見る" }).click();
  await course.getByRole("link", { name: /線形探索を復習する/ }).click();
  await page.getByRole("button", { name: "0", exact: true }).click();
  await expect(page.locator("#nextLesson")).toHaveAttribute("href", "#learn/binary");
  await page.getByRole("link", { name: "全教材を見る" }).click();
  await page.reload();
  await expect(course).toContainText("1 / 4 教材クリア");
  await course.getByRole("link", { name: /二分探索を始める/ }).click();
  await page.getByRole("button", { name: "中央より右" }).click();
  await page.locator("#nextLesson").click();
  await page.getByRole("button", { name: "最大値", exact: true }).click();
  await page.locator("#nextLesson").click();
  await page.getByRole("button", { name: "キュー", exact: true }).click();
  await expect(page.locator("#nextLesson")).toContainText("4教材クリア");
  await page.getByRole("link", { name: "全教材を見る" }).click();
  await expect(course).toContainText("4 / 4 教材クリア");
  await course.getByRole("link", { name: "探索ラボで試す →" }).click();
  await expect(page.locator("#frontierLab")).toBeVisible();
});

test("search cards follow live bounds, invalid edits, rewind and an empty search", async ({ page }) => {
  await page.goto("/#learn/binary");
  await page.getByText("入力を変えて試す", { exact: true }).click();
  const input = page.locator("#lessonInput");
  const run = page.getByRole("button", { name: "この入力で実行" });
  await input.fill('{"values":[1,3,5,7,9],"target":7}');
  await run.click();
  await page.locator("#traceNext").click();
  await expect(page.locator(".guide-tile.selected")).toContainText("5");
  await page.getByRole("button", { name: "左側を候補から外す" }).click();
  await expect(page.locator(".prediction-feedback")).toContainText("正解。 中央の 5");
  await page.locator("#traceNext").click();
  await expect(page.locator(".guide-tile.excluded")).toHaveCount(3);
  await expect(page.locator(".guide-tile.selected")).toContainText("7");
  await page.locator("#tracePrev").click();
  await expect(page.locator(".guide-tile.excluded")).toHaveCount(0);
  await input.fill('{"values":[9,5],"target":9}');
  await run.click();
  await expect(page.getByRole("alert")).toContainText("昇順");
  await expect(page.locator(".guide-tile.selected")).toContainText("5");
  await page.locator("#traceEnd").click();
  await expect(page.locator(".course-diagram figcaption")).toContainText("返す位置は 3");
  await expect(page.locator(".guide-tile.excluded")).toHaveCount(3);
  await input.fill('{"values":[],"target":7}');
  await run.click();
  await expect(page.locator(".course-diagram")).toContainText("札は0枚");
  await page.locator("#traceNext").click();
  await expect(page.locator("#answer")).toHaveText("-1");
  await expect(page.locator(".course-diagram figcaption")).toContainText("見つかりません");
});

test("a swap and a growing queue show what changed on the same trace step", async ({ page }) => {
  await page.goto("/#learn/bubble");
  const tiles = page.locator(".guide-tiles");
  await page.locator("#traceNext").click();
  await expect(tiles.locator(".selected strong")).toHaveText(["7", "2"]);
  await page.getByRole("button", { name: "交換する", exact: true }).click();
  await expect(page.locator(".prediction-feedback")).toContainText("正解");
  await page.locator("#traceNext").click();
  await expect(tiles.locator(".selected strong")).toHaveText(["2", "7"]);
  await expect(page.locator(".course-diagram figcaption")).toContainText("7 が右へ");
  await page.goto("/#learn/bfs");
  await page.locator("#traceNext").click();
  await page.getByRole("button", { name: "末尾に並べる" }).click();
  await expect(page.locator(".prediction-feedback")).toContainText("1、2");
  await page.locator("#traceNext").click();
  await expect(tiles.locator("strong")).toHaveText(["1", "2"]);
  await page.locator("#traceEnd").click();
  await expect(page.locator(".diagram-label")).toHaveText("訪問した順番");
  await expect(tiles.locator("strong")).toHaveText(["0", "1", "2", "3", "4", "5"]);
});
